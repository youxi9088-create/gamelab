const {chromium}=require('../executors/node_modules/playwright');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.argv[2]+'/#candidates');
 await page.locator('#page .gamecard').first().waitFor();
 await page.goto(process.argv[2]+'/#overview');
 await page.getByRole('heading',{name:'游戏生产概览',exact:true}).waitFor();
 if((await page.locator('.production-stats .stat').first().locator('.stat-value').innerText()).replace(/\s/g,'')!=='0个')throw Error('Unaccepted game counted in library metric');
 await page.goto(process.argv[2]+'/#library');
 await page.getByText('还没有已入库游戏',{exact:true}).waitFor();
 await page.goto(process.argv[2]+'/#reviews');
 await page.locator('.review-cards button[data-review]').first().click();
 await page.locator('#review-form input[name="gameplay"]').check();
 await page.locator('#review-form input[name="visual"]').check();
 const response=page.waitForResponse(r=>r.url().endsWith('/approve'));
 await page.locator('#review-form button[type="submit"]').click();
 if((await response).status()!==200)throw Error('Acceptance failed');
 await page.waitForFunction(()=>document.querySelector('#overlay').childElementCount===0);
 if(await page.locator('#pending-reviews .gamecard').count())throw Error('Accepted game still pending');
 await page.locator('.accepted-cards button[data-review]').first().click();
 if(!(await page.locator('#review-form').innerText()).includes('功能验收已通过'))throw Error('Missing completion state');
 if(!(await page.locator('#review-form button[type="submit"]').isDisabled()))throw Error('Unknown rights must not publish');
 await page.goto(process.argv[2]+'/#candidates');
 await page.getByText('暂无待处理的候选游戏',{exact:true}).waitFor();
 if(await page.locator('#page .gamecard').count())throw Error('Accepted game still a candidate');
 await page.goto(process.argv[2]+'/#library');
 await page.locator('#page .gamecard').first().waitFor();
 if(errors.length)throw Error(errors.join('\n'));
 await page.goto(process.argv[2]+'/#overview');
 await page.getByRole('heading',{name:'游戏生产概览',exact:true}).waitFor();
 if((await page.locator('.production-stats .stat').first().locator('.stat-value').innerText()).replace(/\s/g,'')!=='1个')throw Error('Accepted game missing from library metric');
 await browser.close();console.log('Functional acceptance UI passed');
})().catch(e=>{console.error(e);process.exit(1)});
