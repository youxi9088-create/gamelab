const {chromium}=require('../executors/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const errors=[];
 try{
  const page=await browser.newPage({viewport:{width:1280,height:960}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.argv[2]);
  await page.locator('#auth-title').filter({hasText:'初始化任务后台'}).waitFor();
  await page.screenshot({path:'qa-output/task-backend-setup.png'});
  await page.locator('#auth-username').fill('admin');
  await page.locator('#auth-password').fill('fixture-admin-password');
  await page.locator('#auth-submit').click();
  await page.locator('#view-tasks').waitFor();
  await page.locator('#conversion-url').fill('https://example.org/ui-fixture');
  await page.locator('#conversion-form button').click();
  await page.locator('#jobs-body').filter({hasText:'example.org'}).waitFor();
  assert.equal(await page.locator('#jobs-body tr').count(),1);
  await page.locator('#conversion-url').fill('https://example.org/draft-preserved');
  await page.waitForTimeout(16000);
  assert.equal(await page.locator('#conversion-url').inputValue(),'https://example.org/draft-preserved');
  await page.locator('[data-job]').click();
  await page.locator('#job-dialog').waitFor();
  await page.locator('#job-detail').filter({hasText:'过程记录'}).waitFor();
  await page.screenshot({path:'qa-output/task-backend-detail-desktop.png'});
  await page.locator('#close-job').click();
  await page.locator('[data-view="accounts"]').click();
  await page.locator('#new-account').click();
  await page.locator('#account-username').fill('viewer-ui');
  await page.locator('#account-password').fill('fixture-viewer-password');
  await page.locator('#account-form button[type="submit"]').click();
  await page.locator('#accounts-body').filter({hasText:'viewer-ui'}).waitFor();
  await page.screenshot({path:'qa-output/task-backend-accounts-desktop.png',fullPage:true});
  await page.locator('[data-view="tasks"]').click();
  await page.screenshot({path:'qa-output/task-backend-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  const overflow=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth,items:[...document.querySelectorAll('body *')].filter(node=>node.getBoundingClientRect().right>innerWidth+1).slice(0,12).map(node=>({tag:node.tagName,id:node.id,class:node.className,right:node.getBoundingClientRect().right}))}));
  await page.screenshot({path:'qa-output/task-backend-mobile.png',fullPage:true});
  assert(overflow.width<=overflow.viewport+1,JSON.stringify(overflow));
  assert(await page.locator('#logout-mobile').isVisible());
  await page.locator('[data-view="services"]').click();
  await page.locator('#ai-form').waitFor();
  assert(await page.locator('#ai-url').isVisible());
  await page.screenshot({path:'qa-output/task-backend-services-mobile.png',fullPage:true});
  await page.reload();
  await page.locator('#view-services').waitFor();
  assert.equal(await page.locator('#user-name').textContent(),'admin');
  assert.deepEqual(errors,[]);
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
